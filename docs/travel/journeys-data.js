export function getJourneyById(id) {
  return JOURNEYS.find((journey) => journey.id === id) ?? null;
}

export function filterJourneys(journeys, filters = {}) {
  const source = Array.isArray(journeys) ? journeys : [];
  return source.filter((journey) => {
    if (filters.mode && journey.mode !== filters.mode) return false;
    if (filters.region && journey.region !== filters.region) return false;
    if (filters.feeling && !journey.feelings.includes(filters.feeling)) return false;
    if (filters.type && journey.type !== filters.type) return false;
    if (filters.departurePort) {
      const ports = new Set(
        [...(journey.departurePorts ?? []), journey.cruise?.departurePort].filter(Boolean),
      );
      if (!ports.has(filters.departurePort)) return false;
    }
    return true;
  });
}
