function makeJourney(config) {
  const image = art(config.mode);
  return {
    id: config.id,
    type: config.type,
    mode: config.mode,
    title: config.title,
    subtitle: config.subtitle,
    country: config.country,
    region: config.region,
    duration: config.duration,
    feelings: config.feelings ?? [],
    editorialPriority: config.editorialPriority ?? 50,
    hero: {
      eyebrow: config.eyebrow ?? `${config.region} · ${config.mode.toUpperCase()}`,
      title: config.title,
      story: config.subtitle,
      image,
      cta: 'EXPLORE THIS JOURNEY →',
    },
    bestMonths: config.bestMonths ?? [],
    shoulderMonths: config.shoulderMonths ?? [],
    eventMonths: config.eventMonths ?? [],
    avoidMonths: config.avoidMonths ?? [],
    yearRound: Boolean(config.yearRound),
    departurePorts: config.departurePorts ?? [],
    signatureMoments: [
      moment(
        `${config.id}-m1`,
        'SIGNATURE MOMENT',
        config.moments?.[0] ?? 'The first reveal',
        'A scene worth travelling for.',
        image,
      ),
      moment(
        `${config.id}-m2`,
        'THE JOURNEY',
        config.moments?.[1] ?? 'The way through',
        'The movement is part of the experience.',
        image,
      ),
      moment(
        `${config.id}-m3`,
        'THE MEMORY',
        config.moments?.[2] ?? 'The moment that stays',
        'A final image you carry home.',
        image,
      ),
    ],
    route: {
      stops: (config.route ?? [config.region]).map((name, index) => ({
        id: `${config.id}-stop-${index + 1}`,
        name,
        short: '',
      })),
    },
    chapters: [
      chapter(
        'departure',
        'DEPARTURE',
        'The journey begins',
        config.route?.[0] ?? config.region,
        config.subtitle,
        image,
        'departure',
      ),
      chapter(
        'chapter-1',
        'CHAPTER 1',
        config.moments?.[0] ?? 'Arrive inside the story',
        config.region,
        'Slow down enough to notice the place, not just reach it.',
        image,
      ),
      chapter(
        'chapter-2',
        'CHAPTER 2',
        config.moments?.[1] ?? 'Move through the landscape',
        config.region,
        'The route is designed as part of the experience.',
        image,
      ),
      chapter(
        'return',
        'RETURN',
        'The road home',
        config.route?.at(-1) ?? config.region,
        'Leave with a clear ending rather than a rushed checkout.',
        image,
        'return',
      ),
    ],
    operationalDays: [],
    stays: [],
    transport: { mode: config.mode, label: config.transportLabel ?? config.mode },
    pricing: {
      indicative: true,
      label: 'Plan with AGNES',
      disclaimer: 'Editorial journey. Pricing and availability are not live.',
    },
    agnesRules: {
      quickActions: ['Make it shorter', 'More romantic', 'Family-friendly', 'Show the practical plan'],
    },
    media: { hero: image, gallery: [image] },
    ...(config.cruise ? { cruise: config.cruise } : {}),
  };
}

