const art = (mode) => `assets/world/${mode}.svg`;

function makeJourney(config) {
  const image = art(config.mode);
  const route = config.route;
  const title = config.title;
  const operational = {
    timing: 'Curated timing',
    transit: 'Indicative routing',
    note: 'Final timings depend on selected dates and providers.',
  };
  const chapter = (id, label, location, kind = 'leg') => ({
    id,
    kind,
    dayLabel: label,
    title: location,
    location,
    narrative: config.subtitle,
    image,
    operational,
    agnes: 'AGNES can adapt pace and practical detail for this journey.',
  });

  return {
    id: config.id,
    type: config.type,
    mode: config.mode,
    title,
    subtitle: config.subtitle,
    country: config.country,
    region: config.region,
    duration: config.duration,
    feelings: config.feelings,
    editorialPriority: config.priority ?? 72,
    hero: {
      eyebrow: `${config.region} · ${config.mode.toUpperCase()}`,
      title,
      story: config.subtitle,
      image,
      cta: 'EXPLORE THIS JOURNEY →',
    },
    bestMonths: config.months,
    shoulderMonths: config.shoulderMonths ?? [],
    eventMonths: config.eventMonths ?? [],
    avoidMonths: config.avoidMonths ?? [],
    yearRound: Boolean(config.yearRound),
    departurePorts: config.departurePort ? [config.departurePort] : [],
    signatureMoments: config.moments.map((moment, index) => ({
      id: `${config.id}-m${index + 1}`,
      label: index === 0 ? 'SIGNATURE MOMENT' : index === 1 ? 'THE JOURNEY' : 'THE MEMORY',
      title: moment,
      copy: 'A scene worth travelling for.',
      image,
    })),
    route: {
      stops: route.map((name, index) => ({
        id: `${config.id}-stop-${index + 1}`,
        name,
        short: '',
      })),
    },
    chapters: [
      chapter('departure', 'DEPARTURE', route[0], 'departure'),
      chapter('chapter-1', 'CHAPTER 1', route[1]),
      chapter('chapter-2', 'CHAPTER 2', route.at(-2)),
      chapter('return', 'RETURN', route.at(-1), 'return'),
    ],
    operationalDays: [],
    stays: [],
    transport: { mode: config.mode, label: config.mode },
    pricing: {
      indicative: true,
      label: 'Plan with AGNES',
      disclaimer: 'Editorial journey. Pricing and availability are not live.',
    },
    agnesRules: {
      quickActions: ['Make it shorter', 'More romantic', 'Family-friendly'],
    },
    media: { hero: image, gallery: [image] },
    ...(config.type === 'cruise'
      ? {
          cruise: {
            departurePort: config.departurePort,
            returnPort: config.departurePort,
            portsOfCall: route.slice(1, -1),
            ship: { name: 'Curated cruise ship', indicative: true },
            cabinClasses: ['Inside', 'Oceanview', 'Balcony'],
            sampleDepartures: [],
          },
        }
      : {}),
  };
}

